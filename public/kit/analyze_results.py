#!/usr/bin/env python3
"""
Scientific Analysis & Poster Figure Generator
=============================================
Reads `experiment_results.csv` generated by `run_experiment.py`, computes:
  - RQ1: Linear regression slopes (mWh / input token vs. mWh / output token) & 2D Heatmap
  - RQ2: Accuracy vs. Energy Pareto curve & Kneedle Saturation Knee Point
  - RQ3: Energy per Correct Answer (Wh/correct), Delta Acc per Extra Wh, and McNemar's Paired Test

Saves 4 publication-grade 300-DPI PNG figures + `summary_stats.json`.
"""

import argparse
import json
import math
from pathlib import Path
from typing import Dict, Tuple

import numpy as np
import pandas as pd
from scipy import stats


def mcnemar_test(off_correct: np.ndarray, on_correct: np.ndarray) -> Dict[str, object]:
    n11 = int(np.sum((off_correct == 1) & (on_correct == 1)))
    n10 = int(np.sum((off_correct == 1) & (on_correct == 0)))
    n01 = int(np.sum((off_correct == 0) & (on_correct == 1)))
    n00 = int(np.sum((off_correct == 0) & (on_correct == 0)))
    discordant = n10 + n01

    if discordant == 0:
        method = "exact_binomial"
        chi2_val = None
        p_val = 1.0
    elif discordant < 25:
        method = "exact_binomial"
        chi2_val = None
        p_val = float(stats.binomtest(min(n10, n01), n=discordant, p=0.5, alternative="two-sided").pvalue)
    else:
        method = "chi2_edwards"
        chi2_val = float(((abs(n10 - n01) - 1) ** 2) / discordant)
        p_val = float(stats.chi2.sf(chi2_val, df=1))

    return {
        "n11": n11,
        "n10": n10,
        "n01": n01,
        "n00": n00,
        "discordant": discordant,
        "method": method,
        "chi_square": chi2_val,
        "p_value": p_val,
        "significant_05": p_val < 0.05,
        "acc_off_pct": float(np.mean(off_correct) * 100.0) if len(off_correct) else 0.0,
        "acc_on_pct": float(np.mean(on_correct) * 100.0) if len(on_correct) else 0.0,
    }


def detect_knee_limit(pareto_df: pd.DataFrame) -> Tuple[int, float, float]:
    """Finds the Kneedle elbow point on normalized (energy_wh, accuracy_pct)."""
    df = pareto_df.sort_values("energy_wh").reset_index(drop=True)
    if len(df) < 3:
        row = df.iloc[-1]
        return int(row["max_tokens_limit"]), float(row["energy_wh"]), float(row["accuracy_pct"])

    e = df["energy_wh"].to_numpy(dtype=float)
    a = df["accuracy_pct"].to_numpy(dtype=float)
    e_norm = (e - e.min()) / max(1e-9, e.max() - e.min())
    a_norm = (a - a.min()) / max(1e-9, a.max() - a.min())

    x1, y1 = e_norm[0], a_norm[0]
    x2, y2 = e_norm[-1], a_norm[-1]
    chord_len = math.hypot(x2 - x1, y2 - y1) or 1.0

    best_idx = 1
    best_dist = -1e9
    for i in range(1, len(df) - 1):
        dist = ((x2 - x1) * (a_norm[i] - y1) - (y2 - y1) * (e_norm[i] - x1)) / chord_len
        if dist > best_dist:
            best_dist = dist
            best_idx = i

    row = df.iloc[best_idx]
    return int(row["max_tokens_limit"]), float(row["energy_wh"]), float(row["accuracy_pct"])


def analyze(csv_path: str, out_dir: str, skip_plots: bool = False) -> None:
    df = pd.read_csv(csv_path)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    summary: Dict[str, object] = {"total_rows": int(len(df))}

    # ---------------- RQ1: Input vs Output Energy Slopes ----------------
    rq1 = df[df["phase"] == "rq1_sweep"].copy()
    if not rq1.empty:
        min_out = rq1["max_tokens_limit"].min()
        min_in = rq1["input_tokens"].min()
        in_sweep = rq1[rq1["max_tokens_limit"] == min_out].groupby("input_tokens", as_index=False)["energy_wh"].mean()
        out_sweep = rq1[rq1["input_tokens"] <= min_in + 16].groupby("output_tokens", as_index=False)["energy_wh"].mean()

        in_slope, in_int, in_r, _, _ = stats.linregress(in_sweep["input_tokens"], in_sweep["energy_wh"]) if len(in_sweep) >= 2 else (0, 0, 0, 0, 0)
        out_slope, out_int, out_r, _, _ = stats.linregress(out_sweep["output_tokens"], out_sweep["energy_wh"]) if len(out_sweep) >= 2 else (0, 0, 0, 0, 0)

        summary["rq1"] = {
            "input_slope_mwh_per_token": float(in_slope * 1000.0),
            "input_r2": float(in_r ** 2),
            "output_slope_mwh_per_token": float(out_slope * 1000.0),
            "output_r2": float(out_r ** 2),
            "output_to_input_ratio": float(out_slope / in_slope) if in_slope > 1e-12 else 0.0,
        }

    # ---------------- RQ2: Output Limit Pareto & Knee ----------------
    rq2 = df[(df["phase"] == "rq2_limits") & (df["limit_type"] == "num_predict")].copy()
    if not rq2.empty:
        pareto = (
            rq2.groupby("max_tokens_limit", as_index=False)
            .agg(
                energy_wh=("energy_wh", "mean"),
                accuracy_pct=("correct", lambda s: float(s.mean() * 100.0)),
                total_energy=("energy_wh", "sum"),
                total_correct=("correct", "sum"),
            )
        )
        pareto["wh_per_correct"] = pareto["total_energy"] / pareto["total_correct"].clip(lower=1)
        knee_lim, knee_e, knee_acc = detect_knee_limit(pareto)
        summary["rq2"] = {
            "knee_limit_tokens": knee_lim,
            "knee_energy_wh": knee_e,
            "knee_accuracy_pct": knee_acc,
            "pareto_table": pareto.to_dict(orient="records"),
        }

    # ---------------- RQ3: Paired Thinking ON vs OFF & McNemar ----------------
    rq3 = df[df["phase"] == "rq3_thinking"].copy()
    if not rq3.empty:
        pivoted = rq3.pivot_table(index=["dataset", "prompt_id"], columns="thinking_mode", values="correct", aggfunc="first").dropna()
        if "off" in pivoted.columns and "on" in pivoted.columns:
            overall_mc = mcnemar_test(pivoted["off"].to_numpy(), pivoted["on"].to_numpy())
            by_ds = {}
            for ds_name, sub in pivoted.groupby(level=0):
                by_ds[str(ds_name)] = mcnemar_test(sub["off"].to_numpy(), sub["on"].to_numpy())

            # Energy per correct answer & extra accuracy per extra Wh
            e_stats = rq3.groupby(["dataset", "thinking_mode"], as_index=False).agg(
                mean_wh=("energy_wh", "mean"),
                total_wh=("energy_wh", "sum"),
                total_correct=("correct", "sum"),
                acc_pct=("correct", lambda s: float(s.mean() * 100.0)),
            )
            e_stats["wh_per_correct"] = e_stats["total_wh"] / e_stats["total_correct"].clip(lower=1)

            summary["rq3"] = {
                "mcnemar_overall": overall_mc,
                "mcnemar_by_dataset": by_ds,
                "efficiency_summary": e_stats.to_dict(orient="records"),
            }

    stats_path = out / "summary_stats.json"
    stats_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"[INFO] Saved statistical summary -> {stats_path}")

    if not skip_plots:
        import matplotlib.pyplot as plt

        plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})

        # Figure 1: RQ1 Token Scaling
        if not rq1.empty:
            fig, ax = plt.subplots(figsize=(6.5, 4.2), dpi=300)
            ax.plot(in_sweep["input_tokens"], in_sweep["energy_wh"] * 1000, "o-", color="#1D4ED8", label="Input Tokens (Prefill)")
            ax.plot(out_sweep["output_tokens"], out_sweep["energy_wh"] * 1000, "s-", color="#B91C1C", label="Output Tokens (Decode)")
            ax.set_xlabel("Token Count")
            ax.set_ylabel("Energy per Query (mWh)")
            ax.set_title("RQ1: Prefill (Input) vs. Decode (Output) Energy Scaling")
            ax.legend(frameon=False)
            ax.grid(alpha=0.25)
            fig.tight_layout()
            fig.savefig(out / "fig1_token_scaling.png")
            plt.close(fig)

            # Figure 2: 2D Heatmap
            pivot_hm = rq1.pivot_table(index="output_tokens", columns="input_tokens", values="energy_wh", aggfunc="mean")
            fig, ax = plt.subplots(figsize=(6.8, 4.2), dpi=300)
            im = ax.imshow(pivot_hm.values * 1000, aspect="auto", cmap="YlOrRd", origin="lower")
            ax.set_xticks(range(len(pivot_hm.columns)))
            ax.set_xticklabels([str(int(c)) for c in pivot_hm.columns])
            ax.set_yticks(range(len(pivot_hm.index)))
            ax.set_yticklabels([str(int(r)) for r in pivot_hm.index])
            ax.set_xlabel("Input Length (tokens)")
            ax.set_ylabel("Output Length (tokens)")
            ax.set_title("Energy Heatmap (mWh): Input x Output Length")
            cbar = fig.colorbar(im, ax=ax)
            cbar.set_label("Energy (mWh)")
            fig.tight_layout()
            fig.savefig(out / "fig2_heatmap.png")
            plt.close(fig)

        # Figure 3: RQ2 Pareto Knee
        if not rq2.empty:
            fig, ax = plt.subplots(figsize=(6.5, 4.2), dpi=300)
            ax.plot(pareto["energy_wh"] * 1000, pareto["accuracy_pct"], "o-", color="#0F766E", linewidth=2)
            for _, r in pareto.iterrows():
                ax.annotate(f"{int(r['max_tokens_limit'])} tok", (r["energy_wh"] * 1000, r["accuracy_pct"]), xytext=(5, 5), textcoords="offset points", fontsize=8)
            ax.scatter([knee_e * 1000], [knee_acc], s=140, color="#B91C1C", zorder=5, label=f"Knee ({knee_lim} tok)")
            ax.set_xlabel("Mean Energy per Query (mWh)")
            ax.set_ylabel("Verifiable Accuracy (%)")
            ax.set_title("RQ2: Accuracy vs. Energy Pareto Frontier & Saturation Knee")
            ax.legend(frameon=False)
            ax.grid(alpha=0.25)
            fig.tight_layout()
            fig.savefig(out / "fig3_pareto_knee.png")
            plt.close(fig)

        print(f"[INFO] Saved publication figures to {out}/")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Analyze local Ollama + CodeCarbon experiment results.")
    parser.add_argument("--csv", default="experiment_results.csv", help="Path to experiment_results.csv")
    parser.add_argument("--out-dir", default="figures", help="Directory for output plots and JSON summary")
    parser.add_argument("--skip-plots", action="store_true", help="Compute summary_stats.json without rendering matplotlib plots")
    args = parser.parse_args()
    analyze(args.csv, args.out_dir, skip_plots=args.skip_plots)
